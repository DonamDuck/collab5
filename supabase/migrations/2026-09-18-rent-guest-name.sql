-- 하루 가게 — 이용자 성함(실명) (2026-09-18 대표)
-- 대표: 「실명 확인 당일날도 필요하고. 이거 신청할 때 약관 동의 같은 데 넣어야 할 수도 있겠다.」
-- 신청 폼이 「이용하실 분 성함(실명)」을 필수로 받는다. 사장님이 요청 메일·내 하루 가게·연락처에서 이 이름을 먼저 본다.
-- ⭐추가만 한다. 옛 예약은 빈 값으로 남고, 화면·메일은 그때 프로필 브랜드명으로 물러선다. 두 번 돌려도 된다.
-- ⚠️코드 배포보다 먼저 돌린다. 새 신청(insert)이 이 칸을 적어서, 칸이 없으면 신청이 막힌다.

