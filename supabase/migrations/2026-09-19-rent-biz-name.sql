-- 하루 가게 — 상호 칸 (2026-09-19 대표 [J])
-- 대표: 「매장 전화번호는 공개 상세에서 빼자!」 + 판매자 정보는 여기어때·스마트스토어처럼 별도 화면(`/rent/[slug]/seller`)에서
--   결제 전에 보인다. 전자상거래법 제20조②가 청약 전에 주라고 한 값(상호·대표자·주소·전화·사업자번호) 중 «상호»만 칸이 없었다.
--
-- ⭐추가만 한다. 두 번 돌려도 된다(if not exists).
-- ⭐코드는 이 SQL «전»에도 돈다.
--   · 읽기: 칸이 없으면 빈 값으로 읽고, 판매자 정보 화면이 공간 이름을 「(공간 이름)」 표시와 함께 대신 쓴다.
--   · 저장: 칸이 없으면 이 칸만 빼고 저장한다(`spaces.ts` saveSpace). 그 사이 사장님이 적은 상호는 SQL 뒤에 다시 적어야 한다.
-- 옛 공간은 빈 문자열로 남는다. 고치기 화면에서 채우라고 안내한다(새 공간은 필수).
alter table spaces
  add column if not exists biz_name text not null default '';
