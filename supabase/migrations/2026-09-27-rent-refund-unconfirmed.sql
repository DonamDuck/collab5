-- 무엇이 달라지나
--   손님이 취소했는데 토스가 200을 주면서 «그 취소»의 결제 객체가 아닌 본문을 주면, 이제 성공으로 읽지 않는다(`cancelResponseProblem`).
--   그때 예약은 그대로 두고(결제 완료·확정) 이 칸에 시각을 적는다. 정산 화면 「손이 필요한 예약」에
--   「환불을 확인하지 못한 취소」로 뜨고, 관리자가 토스 관리자 화면에서 푼다.
--   ⚠️같은 멱등키로 다시 불러도 토스는 첫 응답을 그대로 준다(15일). 손님이 다시 눌러서는 안 풀려서 표시가 필요하다.
--
-- 칸 하나
--   · refund_unconfirmed_at  표시한 시각. 비어 있으면 표시 없음. 이 칸이 있는 예약은
--                            ① 손님이 다시 취소하려 해도 토스를 부르지 않고 「확인하고 있어요」로 멈추고
--                            ② 정리 작업이 이용 완료·지급 대기로 넘기지 않는다(돈이 돌아갔는지 모르니까).
--   ⏳푸는 버튼은 아직 없다. 토스에서 처리한 뒤엔 이 칸을 비우고 예약·결제 줄을 맞춰야 한다(보고서 제안).
--
-- ⭐추가만 한다. 두 번 돌려도 된다(if not exists). 표·행·정책·함수는 안 건드린다.
-- ⭐코드는 이 SQL «전»에도 돈다.
--   · 읽기: 칸이 없으면 늘 비어 있는 것으로 읽는다(`select *`로 읽고 코드에서 본다).
--   · 표시: 칸이 없으면 적기가 실패하고 콘솔에 남는다. 그래도 손님 말·슬랙 알림·예약 그대로 두기는 똑같이 된다.
--   · 목록: 칸이 없으면 「환불을 확인하지 못한 취소」 조회만 빈다(나머지 두 목록은 그대로).
alter table space_bookings
  add column if not exists refund_unconfirmed_at timestamptz;

