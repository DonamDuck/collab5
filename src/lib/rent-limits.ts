// 하루 가게 — 사람이 적는 칸의 상한과 모양 (2026-09-18 밤 QA SEC-07)
//
// ⭐화면(`maxLength`·칸 밑 오류)과 서버 액션이 «같은 숫자»를 쓴다. 화면 숫자를 따로 적으면 화면은 받아 주고 서버는 돌려보내는 날이 온다.
// 🩸전엔 신청의 「무엇을 하실지」·사장님이 남기는 말·매장 전화에 서버 상한이 없었다. 액션은 화면 없이도 불리니
//   아주 긴 글이나 전화가 아닌 글이 예약 행·공간 행에 그대로 들어가 메일과 목록 카드로 퍼질 수 있었다.
// 🚨훅도 DB도 안 부른다. 클라이언트·서버 어디서든 불린다.

/** 신청 「그날 무엇을 하실지」. 긴 글 목 케이스(443자)의 두 배가 넘는다. */
export const PLAN_MAX = 1000;
/** 사장님이 수락·거절하며 손님께 남기는 말(`host_message`). 환불 신청 사유와 같은 상한이다. */
export const HOST_MESSAGE_MAX = 500;
/** 매장 전화 칸 글자 수(하이픈·괄호·띄어쓰기 포함). 가장 긴 모양 `0507-1234-5678`도 14자다. */
export const CONTACT_PHONE_MAX = 20;

/** 🙋공간 정원과 신청 인원의 상한 (09-18 밤 QA G-08·H-25).
 *  정원을 적지 않은 공간에도 이 값까지만 받는다. 칸이 `integer`라 큰 수는 「저장에 실패했어요」로만 떨어졌고,
 *  음수·0·소수는 그대로 들어갔다. ⭐1,000명은 하루 가게에서 나올 수 있는 값의 바깥 울타리다(가장 큰 목 데이터가 120명). */
export const CAPACITY_MAX = 1000;

/** ☎️매장 전화 모양 — 숫자만 세어 본다.
 *  · `0`으로 시작하는 9~12자리: 지역번호(02 포함)·휴대폰·070, 그리고 네이버 스마트콜 같은 `0507` 안심번호(12자리)
 *  · `15`~`19`로 시작하는 8자리 대표번호(`1588-0000`)
 *  ⚠️손님 번호 규칙(`0`으로 시작하는 9~11자리, `startBookingAction`)보다 넓다. 가게 번호는 안심번호·대표번호가 흔해서
 *    손님 규칙을 그대로 쓰면 네이버 지도에 올려 둔 번호를 못 적는다. */
export function storePhoneOk(v: string): boolean {
  const d = (v ?? "").replace(/\D/g, "");
  return /^0\d{8,11}$/.test(d) || /^1[5-9]\d{6}$/.test(d);
}
