/** 📨메일 «이용 안내» 칸이 연락 규칙(`CONTACT_RULE_GUEST`) 뒤에 덧붙이는 한 줄(09-18 메일 전수).
 *  규칙이 이미 「문자나 전화로」를 말해서, `accessHowLine`을 그대로 붙이면 같은 말이 두 번 나왔다.
 *  그래서 규칙에 없는 «만나서 안내»만 더한다. 문자·전화만 고른 사장님이면 덧붙일 말이 없다. */
export function accessMeetLine(how: AccessHow): string {
  if (how === "onsite") return accessHowLine("onsite");
  if (how === "both") return "이용하시기 전에 사장님이 직접 만나서 한 번 더 알려 드려요.";
  return "";
}

/** ☎️확정된 손님에게 여는 연락처. **가게 전화가 먼저다** — 사장님 개인 번호보다 그쪽이
 *  받는 사람도 편하고, 호스트 약관 제6조가 공개하기로 한 것도 그 번호다.
 *  ⚠️둘 다 없을 수 있다. 그때 빈 칸을 내보내면 손님이 「우리가 빠뜨렸다」고 읽으니 문장으로 말한다. */
export function hostContactLine(shopPhone: string, personalPhone?: string, email?: string): string {
  const parts = [shopPhone?.trim(), personalPhone?.trim(), email?.trim()].filter(Boolean);
  // ✍️09-18 밤 QA(H-30) — 화면 세 곳이 「안 적으셨어요」와 「안 남기셨어요」를 섞어 썼다. 「남기다」 쪽으로 모았다.
  return parts.length > 0 ? Array.from(new Set(parts)).join(" · ") : "연락처를 안 남기셨어요";
}

/** ☎️전화 링크의 `tel:` 값 — **적힌 글에서 첫 번째 번호만 뽑는다**(09-18 밤 QA G-19).
 *
 *  🩸사장님이 매장 전화 칸에 「02-1234-5678 (점심시간엔 안 받아요)」처럼 메모를 같이 적는다. 그런데 세 화면이
 *    `replace(/[^0-9+]/g, "")`로 숫자가 아닌 글자를 «지우기»만 해서, 메모 안의 숫자까지 번호에 붙었다.
 *    「02-1234-5678, 010-2222-3333」이면 두 번호가 한 줄로 이어져 **아무 데도 안 걸리는 번호**가 만들어진다.
 *    화면에 적힌 글자는 멀쩡하고 누른 사람만 안 걸린다 — 눈으로는 못 잡는 종류의 고장이다.
 *  ⭐지우지 말고 «첫 덩어리»를 고른다. 국번 사이의 `-`·공백·괄호는 번호의 일부라 안에서만 허용한다.
 *  ⚠️못 찾으면 빈 문자열이다. 호출부는 그때 링크 대신 글자만 보여 준다(`tel:`이 비면 눌러도 아무 일이 없다). */
export function telHref(raw: string): string {
  const s = (raw ?? "").trim();
  const intl = s.startsWith("+");
  // 숫자와 하이픈만 번호의 일부다. 한글·쉼표·슬래시·괄호는 «끊는 자리»라 거기서 토막을 낸다.
  const tokens = s.split(/[^0-9-]+/).map((t) => t.replace(/\D/g, "")).filter(Boolean);
  let out = "";
  for (const t of tokens) {
    // 「02 1234 5678」처럼 사이를 띄어 쓴 한 번호는 이어 붙이고, 번호 하나를 다 모았으면 거기서 멈춘다.
    if (out.length >= 8 || out.length + t.length > 11) break;
    out += t;
  }
  if (out.length < 4) return "";
  return intl ? `+${out}` : out;
}

