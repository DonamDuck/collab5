// 🔻`Link`·`Reveal` import 제거(08-16) — 마무리 CTA 섹션이 사라지면서 홈에서 쓰는 곳이 없어졌다.
//    ⚠️`Reveal` 컴포넌트 자체는 남아 있다(다른 페이지가 쓴다). 홈만 안 쓰는 것.
import { repo } from "@/lib/repo";
import { HomeBody } from "./HomeBody";

// 🔄~~n≤12 동안 전량 노출~~(07-31) → 08-16부터 캐러셀만 그린다(`BrandGrid`의 `CAROUSEL_LIMIT`, ~~6~~→**7** 08-20).
//   ⚠️여기서 자르지 않는 이유 — 레일 끝 칸이 「**N곳** 모두 보기」로 **전체 수**를 말해야 하고,
//     칩(C2)도 전체 목록을 봐야 "실제 등록된 유형"을 가릴 수 있다. 자르는 건 화면의 일이다.
const GRID_LIMIT = 24;

// ⭐홈 노출 순서 — 대표가 직접 정한다(08-02). 08-16부터 **가로 캐러셀 앞 N개**가 이 순서를 쓴다
//   (N = `BrandGrid`의 `CAROUSEL_LIMIT`, 08-20에 6→7). 여기 없는 slug는 맨 뒤로 밀린다.
//   ⚠️이름이 아니라 **slug**로 잡는다 — 상호는 사장님이 바꿀 수 있지만 slug는 안 바뀐다.
const HOME_ORDER: string[] = [
  "m-ofjghi", // 캔버스가든
  "m-vs9xzg", // 호락호락도서관
  "m-uako9s", // 아그레아블
  "m-oblejt", // 계단뿌셔클럽
  "m-irywef", // 두더지요가원
  "m-7lefr9", // 전종원 작가        ← 08-20 추가(대표 지시 "종원작가님 소개서도 넣어주라")
  //   ⚠️여섯 번째에 끼운 건 **앞 5곳의 자리를 그대로 두려고**서다. 이걸 넣자 캔앤코르크가
  //     7번으로 밀려 레일 밖이 됐는데, 순서를 다투는 대신 **캐러셀 칸을 6→7로 늘려**
  //     해결했다(대표 지시 08-20 — `BrandGrid`의 `CAROUSEL_LIMIT`). 지금은 10곳 중 7곳이 보인다.
  "m-u8y5i3", // 캔앤코르크        ← 08-19 콜마페와 자리 맞바꿈(대표 지시)
  "m-8r5gep", // 콜렉트마이페이보릿  ← 08-19에 7번째로 내려갔고, 08-20 전종원 합류로 지금은 8번째.
  //   캐러셀(앞 7개) 밖이지만 「모두 보기」엔 그대로 있다
  "m-x3djf8", // 레이지오터
  "m-vzrlhz", // 로컬페이지        ← 08-20 slug 정정. ~~m-1vv8kj~~는 **죽은 주소**였다
  //   (열면 「소개서를 찾을 수 없어요」). 그 줄이 아무 일도 안 하는 사이 살아 있는 로컬페이지는
  //   이 목록에 없어 `MAX_SAFE_INTEGER`로 맨 뒤에 밀려 있었다 — 순서가 지정된 적이 없던 셈.
];

// ⚠️이 한 줄이 없으면 목록이 **배포 시점에 얼어붙는다**(서버 컴포넌트 프리렌더 함정, /search·/my와 동일).
export const revalidate = 300;

export default async function Home() {
  const fetched = await repo.listHomeMakers(GRID_LIMIT);
  // 매거진 배너용 — 최신 1편만 쓴다.
  // ⚠️홈은 ISR 300초라 새 글이 배너에 뜨기까지 최대 5분 걸린다. `/magazine`은 force-dynamic이라
  //   즉시 뜨므로, 발행 직후 두 화면이 잠깐 어긋나는 건 **버그가 아니라 설계**다.
  const articles = await repo.listPublishedArticles();
  const leadArticle = articles[0];
  const rank = (slug: string) => {
    const i = HOME_ORDER.indexOf(slug);
    return i === -1 ? Number.MAX_SAFE_INTEGER : i;
  };
  const collabBrands = [...fetched].sort((a, b) => rank(a.slug) - rank(b.slug));

  return (
    <HomeBody
      brands={collabBrands}
      article={leadArticle}
      isFirstIssue={articles.length === 1}
      // 🎨확정 배경 = **카본 #0c0c0c**(대표 08-16 2차, 홈 full 비교 후 선택).
      //    후보였던 키위(#98FF5C)는 반려 — 배너를 원색으로 깔면 아래 Kiwi CTA와 색이 겹친다.
      //    잉크(#222222)보다 한 단 어두워 지면이 확실히 닫히고 커버 사진·흰 배지가 더 튄다.
      bannerBg="carbon"
    />
  );
}
